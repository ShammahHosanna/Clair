let lang = 'fr';

export function setLang(code) {
  if (['fr', 'en', 'pcm'].includes(code)) lang = code;
}

export function getLang() {
  return lang;
}

export function t(key, vars = {}) {
  const table = STR[lang] || STR.fr;
  let s = table[key] ?? STR.fr[key] ?? key;
  for (const [k, v] of Object.entries(vars)) {
    s = s.replaceAll(`{${k}}`, v);
  }
  return s;
}

export function voiceCode() {
  const l = LANGS.find(l => l.code === lang) || LANGS[0];
  return l.voice;
}
